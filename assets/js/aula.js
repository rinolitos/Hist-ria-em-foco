// ========================================
// VIDEOAULA
// ========================================

function loadVideo() {

    const video = document.getElementById("lesson-video");
    const placeholder = document.getElementById("video-placeholder");

    video.removeAttribute("src");

    video.hidden = true;
    placeholder.hidden = false;

    if (!moduleData.videoUrl) {
        return;
    }

    try {

        const videoUrl = new URL(moduleData.videoUrl);

        if (videoUrl.protocol !== "https:") {
            return;
        }

        video.src = videoUrl.href;

        video.hidden = false;
        placeholder.hidden = true;

    } catch (error) {

        console.error("URL da videoaula inválida:", error);

    }

}


// ========================================
// LISTA DE TODOS OS MÓDULOS
// ========================================

function loadModuleList() {

    const container = document.getElementById("lesson-module-list");

    container.replaceChildren();

    Object.entries(modules).forEach(([slug, module]) => {

        const link = createElement("a", "");

        link.href = `aula.html?modulo=${encodeURIComponent(slug)}`;

        const number = createElement(
            "span",
            "",
            module.number
        );

        const title = createElement(
            "span",
            "",
            module.title
        );

        link.append(number, title);

        if (slug === currentSlug) {

            link.classList.add("active");

            link.setAttribute("aria-current", "page");

        }

        container.appendChild(link);

    });

}


// ========================================
// NAVEGAÇÃO ENTRE MÓDULOS
// ========================================

function loadModuleNavigation() {

    const moduleSlugs = Object.keys(modules);

    const currentIndex = moduleSlugs.indexOf(currentSlug);

    const previousButton = document.getElementById("previous-module");
    const nextButton = document.getElementById("next-module");

    if (currentIndex > 0) {

        const previousSlug = moduleSlugs[currentIndex - 1];

        previousButton.href =
            `aula.html?modulo=${encodeURIComponent(previousSlug)}`;

        previousButton.textContent =
            `← ${modules[previousSlug].title}`;

        previousButton.hidden = false;

    }

    if (currentIndex < moduleSlugs.length - 1) {

        const nextSlug = moduleSlugs[currentIndex + 1];

        nextButton.href =
            `aula.html?modulo=${encodeURIComponent(nextSlug)}`;

        nextButton.textContent =
            `${modules[nextSlug].title} →`;

        nextButton.hidden = false;

    }

}


